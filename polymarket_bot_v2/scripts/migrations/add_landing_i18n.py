LANG_MAP = {
    "en": EN,
    "zh-CN": ZH_CN,
    "es": ES,
    "fr": FR,
    "ja": JA,
    "ko": KO,
    "pt": PT,
    "th": TH,
    "vi": VI,
}


def main():
    force = "--force" in sys.argv
    for lang, payload in LANG_MAP.items():
        path = I18N_DIR / f"{lang}.json"
        if not path.exists():
            print(f"  ! missing: {path}")
            continue
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        added = 0
        replaced = 0
        for k, v in payload.items():
            if k in data:
                if force and data[k] != v:
                    data[k] = v
                    replaced += 1
            else:
                data[k] = v
                added += 1
        # Re-sort keys alphabetically (matches existing convention).
        data = {k: data[k] for k in sorted(data.keys())}
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"  {lang}.json: +{added} added, ~{replaced} replaced")


if __name__ == "__main__":
    main()
